package org.example.aiagent.sse;

/**
 * SSE 事件类型枚举。
 * <p>
 * 前端按这些值区分「思考」「工具调用」「最终回答」，从而给出不同的视觉样式。
 */
public enum SseEventType {

    /**
     * 智能体开始处理某个步骤。
     */
    STEP_START,

    /**
     * 思考过程（模型输出的推理文本，非最终答案）。展示为灰色/斜体的折叠块。
     */
    THINK,

    /**
     * 决定调用某个工具，载荷含工具名与参数。
     */
    TOOL_CALL,

    /**
     * 工具执行完成，载荷含工具名与返回结果。
     */
    TOOL_RESULT,

    /**
     * 最终回答正文。展示为正常气泡，流式追加。
     */
    ANSWER,

    /**
     * 正常结束。
     */
    DONE,

    /**
     * 用户主动停止（点击了停止按钮，或关闭了页面）。
     */
    STOPPED,

    /**
     * 执行出错。
     */
    ERROR
}
